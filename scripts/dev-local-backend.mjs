import { spawn } from 'node:child_process';
import { createServer, request as httpRequest } from 'node:http';
import { createConnection } from 'node:net';
import { randomBytes } from 'node:crypto';
import { chmod, lstat, mkdir, open, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { clearTimeout, setTimeout } from 'node:timers';
import { fileURLToPath } from 'node:url';

// Local Docker only. This never links a project, loads application env files,
// changes hosted settings, resets a database or modifies mobile configuration.
// Supabase's documented localhost network pattern:
// https://supabase.com/docs/guides/local-development
const root = fileURLToPath(new URL('../', import.meta.url));
const workdir = join(root, '.cache/local-supabase');
const project = 'peekalo-local-testing';
const network = 'peekalo-local-testing-loopback';
const envFile = join(root, 'apps/web/.env.local-testing');
const marker = '# Generated by scripts/dev-local-backend.mjs for isolated local testing.';
const apiOrigin = 'http://127.0.0.1:55321';
const mailOrigin = 'http://127.0.0.1:55324';
const appOrigin = 'http://127.0.0.1:3101';
const mode = process.argv[2] ?? 'start';
let dockerSocket;
const childEnv = Object.fromEntries(Object.entries(process.env).filter(([key]) =>
  !key.startsWith('SUPABASE_') && !['SHARE_TOKEN_SECRET', 'PUBLIC_APP_URL', 'PUBLIC_SITE_URL', 'EXPO_PUBLIC_API_URL'].includes(key)));

async function exists(path) {
  try { return await lstat(path); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}
async function privateWrite(path, content) {
  const current = await exists(path);
  if (current?.isSymbolicLink()) throw new Error('Refusing a symlink destination');
  await writeFile(path, content, { mode: 0o600 });
  await chmod(path, 0o600);
}
async function managedWrite(path, content) {
  const current = await exists(path);
  if (current && (current.isSymbolicLink() || !(await readFile(path, 'utf8')).startsWith(marker))) {
    throw new Error('Refusing to replace an unmanaged local configuration');
  }
  await privateWrite(path, `${marker}\n${content}`);
}
async function command(program, args, name, timeoutMs = 120_000) {
  const bundledCli = join(root, '.cache/supabase-cli/supabase');
  const executable = program === 'supabase' && await exists(bundledCli) ? bundledCli : program;
  const stdoutPath = join(workdir, `${name}.stdout.log`);
  const stderrPath = join(workdir, `${name}.stderr.log`);
  await privateWrite(stdoutPath, ''); await privateWrite(stderrPath, '');
  const stdout = await open(stdoutPath, 'w', 0o600);
  const stderr = await open(stderrPath, 'w', 0o600);
  try {
    await new Promise((resolve, reject) => {
      const child = spawn(executable, args, { cwd: root, env: childEnv, stdio: ['ignore', stdout.fd, stderr.fd] });
      const timer = setTimeout(() => { child.kill('SIGTERM'); }, timeoutMs);
      child.once('error', () => { clearTimeout(timer); reject(new Error(`Local command failed: ${name}`)); });
      child.once('exit', code => {
        clearTimeout(timer);
        if (code === 0) resolve(); else reject(new Error(`Local command failed: ${name}`));
      });
    });
  } finally { await stdout.close(); await stderr.close(); }
  return readFile(stdoutPath, 'utf8');
}
function setValue(config, section, key, value) {
  const escaped = section.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const expression = section ? new RegExp(`(^\\[${escaped}\\]\\s*\\n)([\\s\\S]*?)(?=^\\[|$(?![\\s\\S]))`, 'm') : null;
  const setting = new RegExp(`^${key}\\s*=.*$`, 'm');
  if (!section) {
    if (!setting.test(config)) throw new Error('Missing source configuration setting');
    return config.replace(setting, `${key} = ${value}`);
  }
  const match = config.match(expression);
  if (!match || !setting.test(match[2])) throw new Error('Missing source configuration setting');
  return config.replace(expression, (_, heading, body) => heading + body.replace(setting, `${key} = ${value}`));
}
async function prepare() {
  const configPath = join(workdir, 'supabase/config.toml');
  await mkdir(join(workdir, 'supabase/migrations'), { recursive: true, mode: 0o700 });
  let config = await readFile(join(root, 'supabase/config.toml'), 'utf8');
  const values = [
    ['', 'project_id', JSON.stringify(project)], ['api', 'port', '55321'], ['db', 'port', '55322'],
    ['db', 'shadow_port', '55320'], ['db.pooler', 'port', '55329'], ['db.pooler', 'enabled', 'false'],
    ['db.seed', 'enabled', 'false'], ['realtime', 'enabled', 'false'], ['studio', 'enabled', 'false'],
    ['inbucket', 'enabled', 'true'], ['inbucket', 'port', '55324'], ['storage', 'file_size_limit', '"30MiB"'],
    ['auth', 'site_url', JSON.stringify(appOrigin)],
    ['auth', 'additional_redirect_urls', JSON.stringify([appOrigin, 'peekalo://auth-callback', 'peekalo://reset-password'])],
    ['auth', 'enable_signup', 'true'], ['auth', 'enable_anonymous_sign_ins', 'false'],
    ['auth.email', 'enable_signup', 'true'], ['auth.email', 'enable_confirmations', 'true'],
    ['auth.rate_limit', 'email_sent', '1000'], ['edge_runtime', 'enabled', 'false'], ['analytics', 'enabled', 'false'],
  ];
  for (const [section, key, value] of values) config = setValue(config, section, key, value);
  for (const match of config.matchAll(/^\[(auth\.external\.[^\]]+)\]$/gm)) config = setValue(config, match[1], 'enabled', 'false');
  // No credential interpolation from the shell or a linked cloud project.
  config = config.replace(/"env\([^"\n]*\)"/g, '""');
  await managedWrite(configPath, config);
  const migrations = (await readdir(join(root, 'supabase/migrations'))).filter(name => /^\d+_[a-z0-9_]+\.sql$/.test(name));
  for (const name of migrations) await privateWrite(join(workdir, 'supabase/migrations', name), await readFile(join(root, 'supabase/migrations', name)));
}
async function localDocker() {
  const endpoint = JSON.parse(await command('docker', ['context', 'inspect', '--format', '{{json .Endpoints.docker.Host}}'], 'docker-context'));
  if (!endpoint.startsWith('unix://') || (childEnv.DOCKER_HOST && !childEnv.DOCKER_HOST.startsWith('unix://'))) {
    throw new Error('A local Docker socket is required');
  }
  dockerSocket = endpoint.slice('unix://'.length);
  const info = JSON.parse(await command('docker', ['info', '--format', '{{json .}}'], 'docker-info'));
  if (mode === 'start' && info.MemTotal < 6 * 1024 ** 3) throw new Error('Insufficient Docker memory');
}
async function loopbackNetwork() {
  let networks = JSON.parse(await command('docker', ['network', 'ls', '--format', 'json'], 'docker-networks').then(output => `[${output.trim().split('\n').filter(Boolean).join(',')}]`));
  if (!networks.some(item => item.Name === network)) {
    await command('docker', ['network', 'create', '--driver', 'bridge', '-o', 'com.docker.network.bridge.host_binding_ipv4=127.0.0.1', network], 'docker-network-create');
  }
  networks = JSON.parse(await command('docker', ['network', 'inspect', network], 'docker-network-inspect'));
  if (networks[0]?.Driver !== 'bridge' || networks[0]?.Options?.['com.docker.network.bridge.host_binding_ipv4'] !== '127.0.0.1') {
    throw new Error('The local network must publish only to loopback');
  }
}
const supabaseArgs = ['--workdir', workdir, '--network-id', network];
// Docker Desktop ignores the bridge binding default when the CLI explicitly
// supplies HostIp. Rewrite only this stack's container-create requests BEFORE
// they reach Docker. The private socket forwards the CLI's other local traffic.
async function startWithLoopbackPorts() {
  const socket = join(workdir, 'docker.sock');
  if (await exists(socket)) await unlink(socket);
  const sockets = new Set();
  const proxy = createServer(async (incoming, outgoing) => {
    let body;
    try {
      if (incoming.method === 'POST' && /\/containers\/create(?:\?|$)/.test(incoming.url)) {
        const url = new URL(incoming.url, 'http://localhost');
        if (!new RegExp(`^supabase_[a-z0-9_]+_${project}$`).test(url.searchParams.get('name') ?? '')) throw new Error();
        const chunks = []; let size = 0;
        for await (const chunk of incoming) {
          if ((size += chunk.length) > 4 * 1024 * 1024) throw new Error();
          chunks.push(chunk);
        }
        const data = JSON.parse(Buffer.concat(chunks).toString());
        if (data.HostConfig?.NetworkMode !== network) throw new Error();
        for (const bindings of Object.values(data.HostConfig.PortBindings ?? {})) {
          for (const binding of bindings ?? []) binding.HostIp = '127.0.0.1';
        }
        body = Buffer.from(JSON.stringify(data));
      }
      const headers = { ...incoming.headers };
      if (body) { delete headers['transfer-encoding']; headers['content-length'] = body.length; }
      const upstream = httpRequest({ socketPath: dockerSocket, method: incoming.method, path: incoming.url, headers }, response => {
        outgoing.writeHead(response.statusCode, response.headers);
        response.pipe(outgoing);
      });
      upstream.on('error', () => { if (!outgoing.headersSent) outgoing.writeHead(502); outgoing.end(); });
      incoming.on('aborted', () => upstream.destroy());
      outgoing.on('close', () => upstream.destroy());
      if (body) upstream.end(body); else incoming.pipe(upstream);
    } catch { outgoing.writeHead(400); outgoing.end('Local Docker request rejected'); }
  });
  // Docker exec uses an upgraded connection for streaming database checks.
  proxy.on('upgrade', (request, downstream, head) => {
    const upstream = createConnection({ path: dockerSocket }, () => {
      upstream.write(`${request.method} ${request.url} HTTP/${request.httpVersion}\r\n` +
        Object.entries(request.headers).map(([key, value]) => `${key}: ${value}\r\n`).join('') + '\r\n');
      if (head.length) upstream.write(head);
      downstream.pipe(upstream); upstream.pipe(downstream);
    });
    sockets.add(upstream); upstream.once('close', () => sockets.delete(upstream));
    upstream.on('error', () => downstream.destroy());
    downstream.on('error', () => upstream.destroy());
    downstream.on('close', () => upstream.destroy());
  });
  proxy.on('connection', socket => { sockets.add(socket); socket.once('close', () => sockets.delete(socket)); });
  await new Promise((resolve, reject) => { proxy.once('error', reject); proxy.listen(socket, resolve); });
  await chmod(socket, 0o600);
  const oldHost = childEnv.DOCKER_HOST, oldContext = childEnv.DOCKER_CONTEXT;
  childEnv.DOCKER_HOST = `unix://${socket}`; delete childEnv.DOCKER_CONTEXT;
  try {
    await command('supabase', ['start', ...supabaseArgs, '--exclude', 'studio,postgres-meta,realtime,imgproxy,edge-runtime,logflare,vector,supavisor'], 'supabase-start', 20 * 60_000);
  } finally {
    if (oldHost === undefined) delete childEnv.DOCKER_HOST; else childEnv.DOCKER_HOST = oldHost;
    if (oldContext !== undefined) childEnv.DOCKER_CONTEXT = oldContext;
    for (const socket of sockets) socket.destroy();
    await new Promise(resolve => proxy.close(resolve));
    if (await exists(socket)) await unlink(socket);
  }
}
async function verifyBindings() {
  const ids = (await command('docker', ['ps', '--filter', `name=_${project}`, '--format', '{{.ID}}'], 'docker-project-containers')).trim().split('\n').filter(Boolean);
  if (!ids.length) throw new Error('No local project containers found');
  const containers = JSON.parse(await command('docker', ['inspect', ...ids], 'docker-project-inspect'));
  for (const container of containers) {
    if (!container.Name.endsWith(`_${project}`)) throw new Error('Unexpected local project selection');
    for (const bindings of Object.values(container.NetworkSettings.Ports ?? {})) {
      for (const binding of bindings ?? []) if (binding.HostIp !== '127.0.0.1') throw new Error('Unsafe local port publication');
    }
  }
}
async function writeEnvironment(status) {
  if (status.API_URL !== apiOrigin || !status.ANON_KEY || !status.SERVICE_ROLE_KEY) throw new Error('Unexpected local API configuration');
  const secretPath = join(workdir, 'signing-secret');
  if (!(await exists(secretPath))) await privateWrite(secretPath, randomBytes(32).toString('hex'));
  const secret = (await readFile(secretPath, 'utf8')).trim();
  if (!/^[a-f0-9]{64}$/.test(secret)) throw new Error('Invalid local signing secret');
  await managedWrite(envFile, [
    `SUPABASE_URL=${apiOrigin}`, `SUPABASE_ANON_KEY=${status.ANON_KEY}`, `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    `SHARE_TOKEN_SECRET=${secret}`, `PUBLIC_APP_URL=${appOrigin}`, 'PUBLIC_SITE_URL=http://127.0.0.1:3100',
    'WAITLIST_ENABLED=false', '',
  ].join('\n'));
}

try {
  if (!['start', 'stop'].includes(mode)) throw new Error('Use start or stop');
  await mkdir(workdir, { recursive: true, mode: 0o700 }); await chmod(workdir, 0o700);
  await localDocker();
  if (mode === 'stop') {
    await command('supabase', ['stop', '--project-id', project, '--workdir', workdir], 'supabase-stop');
    console.log('Isolated local backend stopped; its data volumes are preserved.');
  } else {
    await prepare(); await loopbackNetwork();
    console.log('Starting isolated local Supabase; private command output stays in .cache/local-supabase.');
    await startWithLoopbackPorts();
    try { await verifyBindings(); }
    catch {
      await command('supabase', ['stop', '--project-id', project, '--workdir', workdir], 'supabase-unsafe-binding-stop');
      throw new Error('Local backend stopped because port publication was not loopback-only');
    }
    await command('supabase', ['migration', 'up', '--local', ...supabaseArgs], 'supabase-migrations');
    const status = JSON.parse(await command('supabase', ['status', '-o', 'json', ...supabaseArgs], 'supabase-status'));
    let auth, inboxReady = false;
    const deadline = Date.now() + 60_000;
    while (Date.now() < deadline) {
      try {
        const settings = await fetch(`${apiOrigin}/auth/v1/settings`, { headers: { apikey: status.ANON_KEY }, signal: AbortSignal.timeout(5000) });
        if (settings.ok) auth = await settings.json();
        const inbox = await fetch(`${mailOrigin}/api/v1/messages`, { signal: AbortSignal.timeout(5000) });
        inboxReady = inbox.ok;
        if (auth && inboxReady) break;
      } catch { /* Services may still be warming after CLI startup. */ }
      await new Promise(resolve => setTimeout(resolve, 1000));
    }
    if (!auth || auth.external?.google || auth.mailer_autoconfirm !== false) throw new Error('Email confirmation configuration not ready');
    if (!inboxReady) throw new Error('Local email inbox is not ready');
    await writeEnvironment(status);
    console.log(`Local API ready: ${apiOrigin}`);
    console.log(`Local confirmation inbox: ${mailOrigin}`);
    console.log('Separate server configuration: apps/web/.env.local-testing (mode 600; keys not printed).');
    console.log('Stop without wiping data: node scripts/dev-local-backend.mjs stop');
  }
} catch {
  console.error('Local backend setup failed. Private diagnostics remain under .cache/local-supabase; active app configuration and cloud settings are unchanged.');
  process.exitCode = 1;
}
