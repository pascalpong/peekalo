// Export the approved Veil masters at the display densities and icon sizes.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { tokens } from '../packages/design/src/index.ts';
import { brandArtwork } from '../packages/design/src/brand.ts';

const requireWeb = createRequire(new URL('../apps/web/package.json', import.meta.url));
const sharp = process.argv.includes('--check') ? null : requireWeb('sharp');
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
const source = name => new URL(`packages/design/assets/brand/source/${name}.png`, root);
const outputs = new Map();
const manifestPath = new URL('packages/design/assets/brand/exports.json', root);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const masters = Object.fromEntries(await Promise.all(['logo', 'mark'].map(async name => [name, await readFile(source(name))])));
const recipe = {
  generator: sha(await readFile(new URL(import.meta.url))),
  masters: Object.fromEntries(Object.entries(masters).map(([name, bytes]) => [name, sha(bytes)])),
  dimensions: brandArtwork,
  background: tokens.color.background,
};
const saved = check ? JSON.parse(await readFile(manifestPath, 'utf8')) : null;
if (check && JSON.stringify(recipe) !== JSON.stringify(saved.recipe)) {
  throw new Error('Brand export inputs changed. Run pnpm brand:generate and review the artwork.');
}

for (const [name, width, height] of [
  ['logo', brandArtwork.width, brandArtwork.height],
  ['mark', brandArtwork.markWidth, brandArtwork.markHeight],
]) {
  for (const density of [1, 2, 3]) {
    const suffix = density === 1 ? '' : `@${density}x`;
    outputs.set(`packages/design/assets/brand/${name}${suffix}.png`, () => sharp(masters[name])
      .resize(width * density, height * density, { fit: 'contain', background: '#00000000' })
      .png().toBuffer());
  }
}

async function icon(size, markHeight, background) {
  const symbol = await sharp(masters.mark).resize({ height: markHeight }).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background } })
    .composite([{ input: symbol, gravity: 'centre' }]).png().toBuffer();
}

const favicon = () => icon(96, 74, tokens.color.background);
outputs.set('apps/web/app/icon.png', favicon);
outputs.set('apps/site/app/icon.png', favicon);
outputs.set('apps/mobile/assets/icon.png', () => icon(1024, 690, tokens.color.background));
// Android masks the adaptive foreground. Keep its artwork inside the safe zone.
outputs.set('apps/mobile/assets/adaptive-icon.png', () => icon(1024, 580, '#00000000'));

// Pin the approved generated bytes. Sharp can encode the same artwork
// differently across OS/CPU builds, so CI checks the manifest without resizing.
const assets = {};
for (const [name, generate] of outputs) {
  const path = new URL(name, root);
  if (check) {
    const actual = await readFile(path).catch(() => null);
    if (!actual || sha(actual) !== saved.assets[name]) throw new Error(`Brand export differs: ${name}. Run pnpm brand:generate.`);
  } else {
    const expected = await generate();
    await mkdir(fileURLToPath(new URL('./', path)), { recursive: true });
    await writeFile(path, expected);
    assets[name] = sha(expected);
  }
}
if (!check) await writeFile(manifestPath, `${JSON.stringify({ recipe, assets }, null, 2)}\n`);
console.log(`${check ? 'Verified' : 'Generated'} ${outputs.size} canonical Peekalo brand assets.`);
